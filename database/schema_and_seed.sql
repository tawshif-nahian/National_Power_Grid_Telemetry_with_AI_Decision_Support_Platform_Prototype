    frequency_hz NUMERIC(5, 2) NOT NULL,
    fuel_consumption_rate NUMERIC(10, 2) NOT NULL,
    efficiency_pct NUMERIC(5, 2) NOT NULL,
    grid_load_pct NUMERIC(5, 2) NOT NULL,
    carbon_intensity_kg NUMERIC(10, 2) NOT NULL,
    temperature_c NUMERIC(6, 2) NOT NULL,
    status TEXT NOT NULL DEFAULT 'OPTIMAL'
);

CREATE TABLE IF NOT EXISTS public.telemetry_sirajganj (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    power_output_mw NUMERIC(10, 2) NOT NULL,
    voltage_kv NUMERIC(6, 2) NOT NULL,
    frequency_hz NUMERIC(5, 2) NOT NULL,
