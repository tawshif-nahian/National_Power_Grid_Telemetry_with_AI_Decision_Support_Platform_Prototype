DECLARE
    tbl TEXT;
BEGIN
    FOREACH tbl IN ARRAY ARRAY['powerplants', 'telemetry_payra', 'telemetry_titas', 'telemetry_sirajganj', 'fuel_inventory', 'outage_logs', 'historical_records']
    LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_publication_tables
            WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = tbl
        ) THEN
            EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', tbl);
        END IF;
    END LOOP;
END $$;

