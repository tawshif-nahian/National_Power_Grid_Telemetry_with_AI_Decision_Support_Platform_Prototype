-- 3. FUEL INVENTORY & LOGISTICS TABLE (NPP India Benchmark)
CREATE TABLE IF NOT EXISTS public.fuel_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id BIGINT REFERENCES public.powerplants(id) ON DELETE CASCADE,
    plant_code TEXT UNIQUE NOT NULL,
    plant_name TEXT NOT NULL,
    fuel_type TEXT NOT NULL,
    stock_unit TEXT NOT NULL,
    current_stock NUMERIC(12, 2) NOT NULL,
    max_capacity NUMERIC(12, 2) NOT NULL,
    daily_burn_rate NUMERIC(10, 2) NOT NULL,
    days_of_burn NUMERIC(6, 1) NOT NULL,
    gas_pressure_psi NUMERIC(6, 1),
    supply_source TEXT NOT NULL,
    next_shipment_eta TEXT,
    reserve_status TEXT NOT NULL DEFAULT 'NORMAL', -- 'NORMAL', 'CRITICAL' (<7d), 'SUPER-CRITICAL' (<4d)
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. HISTORICAL ARCHIVES & OUTAGE MATRIX
