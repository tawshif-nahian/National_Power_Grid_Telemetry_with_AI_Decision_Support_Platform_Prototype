-- 1. MASTER POWERPLANT REGISTRY (Facilities & Thermodynamic Cost Parameters)
CREATE TABLE IF NOT EXISTS public.powerplants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_code TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    table_name TEXT UNIQUE NOT NULL,
    fuel_type TEXT NOT NULL,
    fuel_category TEXT NOT NULL DEFAULT 'Coal', -- 'Coal', 'Gas', 'Solar'
    region TEXT NOT NULL DEFAULT 'South-West (Barishal)',
    location TEXT NOT NULL DEFAULT 'Patuakhali, Bangladesh',
    capacity_mw NUMERIC(10, 2) NOT NULL,
    dispatchable_mw NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    substation_kv NUMERIC(6, 1) NOT NULL,
    units_count INT NOT NULL DEFAULT 2,
    commissioning_year INT NOT NULL DEFAULT 2020,
    operator TEXT NOT NULL DEFAULT 'BCPCL / BPDB',
    -- Thermodynamic Cost Model Parameters (Week 2 Deliverable)
    heat_rate_btu_kwh NUMERIC(10, 2) NOT NULL DEFAULT 8650.00, -- BTU/kWh
    fuel_unit_price NUMERIC(10, 4) NOT NULL DEFAULT 5.40,      -- $/MMBTU
    vom_cost_per_mwh NUMERIC(10, 2) NOT NULL DEFAULT 3.80,     -- Variable O&M ($/MWh)
    fixed_cost_per_kw_yr NUMERIC(10, 2) NOT NULL DEFAULT 48.00,
    design_efficiency_pct NUMERIC(5, 2) NOT NULL DEFAULT 43.50,
    carbon_factor_kg_mwh NUMERIC(10, 2) NOT NULL DEFAULT 820.00,
    operational_status TEXT NOT NULL DEFAULT 'ONLINE',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

