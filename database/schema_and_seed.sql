    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_code TEXT NOT NULL,
    plant_name TEXT NOT NULL,
    unit_identifier TEXT NOT NULL,
    outage_category TEXT NOT NULL, -- 'FORCED', 'PLANNED', 'RESERVE_SHUTDOWN'
