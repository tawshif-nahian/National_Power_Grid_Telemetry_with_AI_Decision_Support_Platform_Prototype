-- 5. ROW-LEVEL SECURITY (RLS) POLICIES (Admin Read/Write, Authenticated Read)
ALTER TABLE public.cost_model_assumptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cost_model_monthly_2026 ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cost_model_yearly_tariff ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cost_model_capex_breakdown ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow public read on cost_model_assumptions') THEN
        CREATE POLICY "Allow public read on cost_model_assumptions" ON public.cost_model_assumptions FOR SELECT USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow admin update on cost_model_assumptions') THEN
        CREATE POLICY "Allow admin update on cost_model_assumptions" ON public.cost_model_assumptions FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow public read on cost_model_monthly_2026') THEN
        CREATE POLICY "Allow public read on cost_model_monthly_2026" ON public.cost_model_monthly_2026 FOR SELECT USING (true);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow public read on cost_model_yearly_tariff') THEN
        CREATE POLICY "Allow public read on cost_model_yearly_tariff" ON public.cost_model_yearly_tariff FOR SELECT USING (true);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow public read on cost_model_capex_breakdown') THEN
        CREATE POLICY "Allow public read on cost_model_capex_breakdown" ON public.cost_model_capex_breakdown FOR SELECT USING (true);
    END IF;
END $$;

